"use strict";
/**
 * src/eidos-runtime.ts — eidos is MISE- and PITCHFORK-aware: regenerate both
 * from scratch for a product (the forge stamps the runtime wiring, not just
 * the bunfig).
 *
 * WHY: eidos (ex-bun-scaffold) only wrote bunfig.toml. But a bun product in
 * this estate has THREE runtime surfaces:
 *   bunfig.toml      the bun config (form)
 *   mise.toml        the toolchain + tasks (tools)
 *   pitchfork.toml   the supervised daemon stanza (process ground truth)
 *
 * This module emits all three from ONE product spec, borrowing the proven
 * estate patterns (pitchfork daemon shape from estate-mcp-dropin-ship; mise
 * task shape from estate/mise.toml tasks; both are discovery-driven —
 * ports.env SSOT supplies the port, never hardcoded).
 */
import { existsSync, readFileSync } from "node:fs";
import { discoverDropins } from "./scaffold-services.ts";

const PORTS_ENV = "/home/toxic/pens/estate/config/ports.env";
const ESTATE_MISE = "/home/toxic/pens/estate/mise.toml";

export interface EidosProductSpec {
  /** Product id (dashes, never underscores — pitchfork daemon-id convention). */
  name: string;
  /** Entry source (e.g. src/index.ts) — the daemon's exec target. */
  entry: string;
  /** Serve an HTTP health/mcp surface? (default: false = plain script product) */
  serve?: { port?: number; path?: string; kind: "health" | "mcp" };
  /** mise tasks to generate (default: validate/typecheck/test/lint — the eidos gate set). */
  tasks?: Array<"validate" | "typecheck" | "test" | "lint" | "build">;
  /** Toolchain (default bun latest). */
  bun?: string;
}

/** Read the ports.env SSOT and find a free port in the estate range. */
export function nextFreePort(portsEnvText?: string): number {
  const text = portsEnvText ?? (existsSync(PORTS_ENV) ? readFileSync(PORTS_ENV, "utf8") : "");
  const used = new Set(
    Object.values(JSON.parse(JSON.stringify(text.split("\n").reduce((acc, l) => {
      const c = l.split("#")[0].trim();
      if (!c.includes("=")) return acc;
      const [k, v] = c.split("=");
      if (/_PORT$/.test(k.trim()) && /^\d+$/.test(v.trim())) acc[k.trim()] = Number(v.trim());
      return acc;
    }, {} as Record<string, number>)))),
  );
  for (let p = 25200; p < 25299; p++) if (!used.has(p)) return p;
  return 25999;
}

/** Generate mise.toml for a product (the toolchain + task surface). */
export function generateMiseToml(spec: EidosProductSpec): string {
  const tasks = spec.tasks ?? ["validate", "typecheck", "test", "lint"];
  const has = (t: string) => tasks.includes(t as never);
  const taskBlocks: string[] = [];
  if (has("typecheck")) taskBlocks.push(`[tasks.typecheck]\nrun = "bun x tsc --noEmit"\ndescription = "tsgo/tsc gate"`);
  if (has("test")) taskBlocks.push(`[tasks.test]\nrun = "bun test"\ndescription = "bun test suite"`);
  if (has("lint")) taskBlocks.push(`[tasks.lint]\nrun = "bun x biome check src tests"\ndescription = "biome gate"`);
  if (has("validate")) taskBlocks.push(`[tasks.validate]\nrun = "bun run typecheck && bun run test && bun run lint"\ndescription = "the eidos gate"`);
  if (has("build")) taskBlocks.push(`[tasks.build]\nrun = "bun run build"\ndescription = "production build"`);
  return [
    "# mise.toml — generated by eidos (the forge). Hand-editable; regenerate any time.",
    "# Toolchain + tasks for the bun-scaffold gate set.",
    "",
    "[env]",
    `_.file = "${PORTS_ENV}"`,
    "",
    "[tools]",
    `bun = "${spec.bun ?? "latest"}"`,
    "",
    ...taskBlocks,
    "",
  ].join("\n");
}

/** Generate the pitchfork daemon stanza for a serving product. */
export function generatePitchforkStanza(spec: EidosProductSpec): string {
  if (!spec.serve) return `# ${spec.name}: not a serving product — no daemon stanza\n`;
  const port = spec.serve.port ?? nextFreePort();
  const path = spec.serve.path ?? "/health";
  const lines = [
    "",
    `[daemons."${spec.name}"]`,
    `run = "exec bun ${spec.entry}"`,
    `auto = ["start"]`,
    `retry = true`,
    `mise = true`,
    `port = ${port}`,
    `ready_http = "http://127.0.0.1:${port}${path}"`,
    "",
    `[daemons."${spec.name}".health_http]`,
    `url = "http://127.0.0.1:${port}${path}"`,
    `interval = "30s"`,
    `timeout = "5s"`,
    `retries = 3`,
    "",
  ];
  return lines.join("\n");
}

/** Generate the drop-in env block (BUN_*_PORT) from the live SSOT. */
export function generateDropinEnv(): string {
  const dropins = discoverDropins();
  const lines = ["", "# infra drop-ins (eidos — discovered from config/ports.env)"];
  for (const d of dropins) lines.push(`${d.envVar} = "${d.port}"`);
  return lines.join("\n") + "\n";
}

/** The full three-surface emit for a product (bunfig env + mise + pitchfork). */
export function emitRuntimeWiring(spec: EidosProductSpec): {
  miseToml: string; pitchforkStanza: string; dropinEnv: string;
} {
  return {
    miseToml: generateMiseToml(spec),
    pitchforkStanza: generatePitchforkStanza(spec),
    dropinEnv: spec.serve || true ? generateDropinEnv() : "",
  };
}

